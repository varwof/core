// mtlsAdminFixture is a combined "mTLS management server + corresponding client"
// for HTTP tests requiring admin permissions (cert-first: permissions come from certificate PA grants).
type mtlsAdminFixture struct {
	Server *httptest.Server
	Client *http.Client
}

// newMTLSAdminFixture builds an admin-role management certificate with specified grants,
// starts an mTLS test server trusting that certificate, and returns a client with the certificate.
func newMTLSAdminFixture(t *testing.T, h http.Handler, caps ...string) *mtlsAdminFixture {
	t.Helper()
	return newMTLSCertFixture(t, h, "admin", caps...)
}

// newMTLSSuperAdminFixture builds a superadmin-role management certificate with specified grants.
func newMTLSSuperAdminFixture(t *testing.T, h http.Handler, caps ...string) *mtlsAdminFixture {
	t.Helper()
	return newMTLSCertFixture(t, h, "SuperAdmin", caps...)
}

// newMTLSCertFixture builds a management certificate with specified OU role + grants and starts an mTLS test server.
func newMTLSCertFixture(t *testing.T, h http.Handler, ou string, caps ...string) *mtlsAdminFixture {
	t.Helper()
	cert, key := adminTestCert(t, ou, caps...)
	ts := newTestMTLSServer(t, h, cert)

	client := ts.Client()
	leaf, err := tls.X509KeyPair([]byte(pemCert(cert)), []byte(pemKey(key)))
	if err != nil {
		t.Fatal(err)
	}
	if tr, ok := client.Transport.(*http.Transport); ok {
		tr.TLSClientConfig.Certificates = []tls.Certificate{leaf}
	}
	return &mtlsAdminFixture{Server: ts, Client: client}
}

