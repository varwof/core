// adminTestCert builds a management certificate with PA extension (OU=role + grants),
// for mTLS testing (cert-first: permissions = certificate PA grants).
func adminTestCert(t *testing.T, ou string, caps ...string) (*x509.Certificate, crypto.Signer) {
	t.Helper()
	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		t.Fatal(err)
	}
	var grants []ca.Capability
	for _, c := range caps {
		scheme, action := c, c
		if i := strings.Index(c, ":"); i > 0 {
			scheme, action = c[:i], c[i+1:]
		}
		grants = append(grants, ca.Capability{SchemeId: scheme, CapabilityId: action})
	}
	paExt, err := ca.BuildPrincipalAuthorizationExtension(ca.PrincipalAuthorizationConfig{Grants: grants})
	if err != nil {
		t.Fatal(err)
	}
	tmpl := &x509.Certificate{
		SerialNumber: big.NewInt(time.Now().UnixNano()),
		Subject: pkix.Name{
			CommonName:         "test-admin",
			OrganizationalUnit: []string{ou},
		},
		NotBefore:   time.Now().Add(-1 * time.Hour),
		NotAfter:    time.Now().Add(time.Hour),
		KeyUsage:    x509.KeyUsageDigitalSignature | x509.KeyUsageKeyEncipherment,
		ExtKeyUsage: []x509.ExtKeyUsage{x509.ExtKeyUsageClientAuth},
		ExtraExtensions: []pkix.Extension{paExt},
	}
	der, err := x509.CreateCertificate(rand.Reader, tmpl, tmpl, &key.PublicKey, key)
	if err != nil {
		t.Fatal(err)
	}
	cert, err := x509.ParseCertificate(der)
	if err != nil {
		t.Fatal(err)
	}
	return cert, key
}

// newTestMTLSServer starts a test server requiring client mTLS certificates,
// trusting certificates generated by adminTestCert (self-signed, added to ClientCAs).
func newTestMTLSServer(t *testing.T, h http.Handler, certs ...*x509.Certificate) *httptest.Server {
	t.Helper()
	pool := x509.NewCertPool()
	for _, c := range certs {
		pool.AddCert(c)
	}
	ts := httptest.NewUnstartedServer(h)
	ts.TLS = &tls.Config{ClientAuth: tls.RequireAndVerifyClientCert, ClientCAs: pool}
	ts.StartTLS()
	t.Cleanup(ts.Close)
	return ts
}

