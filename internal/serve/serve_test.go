func TestServeAPIBatchFastSkipsDB(t *testing.T) {
	srv := newTestServer(t)
	ts := httptest.NewServer(srv)
	defer ts.Close()

	body := `{"requests":[{"cn":"fast1.example.com","profile":"tls-server"},{"cn":"fast2.example.com","profile":"tls-server"}],"fast":true}`
	resp := authedPost(t, ts, "/api/certs/batch", "application/json", strings.NewReader(body))
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		t.Fatalf("expected 200, got %d", resp.StatusCode)
	}
	var results []batchRespItem
	json.NewDecoder(resp.Body).Decode(&results)
	if len(results) != 2 {
		t.Fatalf("expected 2 results, got %d", len(results))
	}
	for _, r := range results {
		if r.Status != "ok" {
			t.Fatalf("expected ok for %s, got %s: %s", r.CN, r.Status, r.Error)
		}
	}

	// fast:true must NOT persist certs — verify via list API
	resp2 := authedGet(t, ts, "/api/v1/certs?ca=test-ca&cn=fast1.example.com&limit=10")
	defer resp2.Body.Close()
	var list struct {
		Certs []struct {
			CommonName string `json:"common_name"`
		} `json:"certs"`
	}
	json.NewDecoder(resp2.Body).Decode(&list)
	for _, c := range list.Certs {
		if strings.HasPrefix(c.CommonName, "fast") {
			t.Fatalf("fast batch cert %q unexpectedly persisted", c.CommonName)
		}
	}
}
