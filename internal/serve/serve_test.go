func TestCertToJSON(t *testing.T) {
	now := time.Now()
	reason := 1
	rec := &db.CertRecord{
		SerialNumber: "ABC123",
		CAName:       "test-ca",
		Status:       "V",
		Subject:      "CN=test,O=test",
		CommonName:   "test",
		NotBefore:    now,
		NotAfter:     now.Add(365 * 24 * time.Hour),
		Fingerprint:  "abcdef",
		CertDER:      []byte("fake-cert-der-here"),
	}

	j := certToJSON(rec, false)
	if j.SerialNumber != "ABC123" {
		t.Fatalf("expected ABC123, got %q", j.SerialNumber)
	}
	if j.CertPEM != "" {
		t.Fatal("expected empty CertPEM when includePEM=false")
	}

	j2 := certToJSON(rec, true)
	if j2.CertPEM == "" {
		t.Fatal("expected non-empty CertPEM when includePEM=true")
	}

	revokedAt := now.Add(-24 * time.Hour)
	rec.Status = "R"
	rec.RevokedAt = &revokedAt
	rec.RevokeReason = &reason
	j3 := certToJSON(rec, false)
	if j3.RevokedAt == nil || *j3.RevokedAt == "" {
		t.Fatal("expected revoked_at to be set")
	}
	if j3.RevokeReason == nil || *j3.RevokeReason != 1 {
		t.Fatalf("expected revoke_reason=1, got %v", j3.RevokeReason)
	}
}

